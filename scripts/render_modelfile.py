"""Write ollama/Modelfile from jobx.prompts so the system prompt never drifts (tests check it)."""

from pathlib import Path

from jobx.prompts import SYSTEM_PROMPT, USER_TEMPLATE

pre, post = USER_TEMPLATE.split("{text}")
MODELFILE = f'''# Ollama Modelfile for the fine-tuned extractor (GGUF Q4_K_M).
# 1. Download jobx-qwen2.5-1.5b-Q4_K_M.gguf from https://huggingface.co/<your-hf-username>/jobx-qwen2.5-1.5b-gguf
#    into this folder.
# 2. ollama create jobx -f ollama/Modelfile
# 3. ollama run jobx "<paste a job posting>"
#    For schema-constrained output use the API: POST /api/chat with "format": <schema/jobposting.schema.json>.
# Generated by scripts/render_modelfile.py from src/jobx/prompts.py - edit those, not this file.
FROM ./jobx-qwen2.5-1.5b-Q4_K_M.gguf

TEMPLATE """{{{{- if .System }}}}<|im_start|>system
{{{{ .System }}}}<|im_end|>
{{{{ end }}}}{{{{- range $i, $_ := .Messages }}}}{{{{- if eq .Role "user" }}}}<|im_start|>user
{pre}{{{{ .Content }}}}{post}<|im_end|>
{{{{ else if eq .Role "assistant" }}}}<|im_start|>assistant
{{{{ .Content }}}}<|im_end|>
{{{{ end }}}}{{{{- end }}}}<|im_start|>assistant
"""

SYSTEM """{SYSTEM_PROMPT}"""

PARAMETER temperature 0
PARAMETER num_ctx 4096
PARAMETER num_predict 512
PARAMETER stop "<|im_end|>"
PARAMETER stop "<|endoftext|>"
'''

if __name__ == "__main__":
    out = Path(__file__).resolve().parents[1] / "ollama" / "Modelfile"
    out.write_text(MODELFILE)
    print(f"wrote {out}")
