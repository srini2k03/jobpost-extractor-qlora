"""Phase 6: the generated README block (pending until a run exists) and the vLLM Dockerfile."""

from __future__ import annotations

import re
import shutil
from pathlib import Path

from jobx.bench import plan
from jobx.bench.readme import END, PENDING_LINE, START, bench_block, update_readme

ROOT = Path(__file__).resolve().parents[1]
FIX = ROOT / "tests" / "fixtures" / "bench"


def test_readme_block_is_pending_and_current() -> None:
    block = bench_block(ROOT)
    assert PENDING_LINE in block and "**Findings**" not in block
    for c in plan.expand(plan.load_matrix()):
        assert f"| `{c.name}` |" in block
    assert "303.5 L4-minutes" in block and "$4.07" in block
    readme = (ROOT / "README.md").read_text()
    assert f"{START}\n{block}{END}" in readme  # regenerated by `jobx results-table` (CI diff check)
    assert readme.count("**About the regex baseline.**") == 1


def test_readme_block_with_fixture_results(tmp_path: Path) -> None:
    from jobx.bench.report import report

    shutil.copytree(ROOT / "configs", tmp_path / "configs")
    shutil.copytree(FIX / "manifests", tmp_path / "results/bench/manifests")
    shutil.copytree(FIX / "metrics", tmp_path / "results/metrics")
    report(
        raw_dir=FIX / "raw",
        manifest_dir=tmp_path / "results/bench/manifests",
        metrics_dir=tmp_path / "results/metrics",
        out_dir=tmp_path / "results/bench",
        matrix_path=tmp_path / "configs/bench/matrix.yaml",
        charts=False,  # CI has no matplotlib; chart links appear only for charts that exist
    )
    block = bench_block(tmp_path)
    assert PENDING_LINE not in block and "**Results**" in block
    assert "| 1.5B BF16 | c" in block and "| 3B BF16 | - | - |" in block and "pending |" in block
    assert re.search(r"AWQ 4-bit gave \*\*\d+\.\d\dx\*\* the peak output tokens/s of BF16 on `extract-full`, at "
                     r"\*\*2\.0\*\* points of micro-F1 drop", block)  # fmt: skip
    assert "Prefix caching cut TTFT p95 by **" in block and "Cheapest config for TTFT p95" in block
    assert "FP8" not in block.split("**Findings**")[1]  # not measured -> no sentence
    assert "![" not in block
    (tmp_path / "results/bench/charts").mkdir()
    (tmp_path / "results/bench/charts/prefix_caching_ttft.png").write_bytes(b"png")
    assert "![prefix caching TTFT](results/bench/charts/prefix_caching_ttft.png)" in bench_block(tmp_path)

    readme = tmp_path / "README.md"
    readme.write_text(f"# x\n{START}\nold\n{END}\ntail\n")
    assert update_readme(readme, block) and readme.read_text() == f"# x\n{START}\n{block}{END}\ntail\n"
    assert not update_readme(tmp_path / "configs/bench/matrix.yaml", block)


def test_vllm_dockerfile_pins_the_benchmark_release() -> None:
    text = (ROOT / "docker/Dockerfile.vllm").read_text()
    m = plan.load_matrix()
    assert f"FROM vllm/vllm-openai:v{m['vllm_version']}\n" in text
    awq = next(c for c in plan.expand(m) if c.name == "q15-awq")
    env = dict(re.findall(r"^(?:ENV)?\s*([A-Z_]+)=(\S+?)(?: \\)?$", text, flags=re.M))
    assert env["MODEL"] == awq.model and env["QUANTIZATION"] == awq.quantization and env["DTYPE"] == awq.dtype
    assert int(env["MAX_NUM_SEQS"]) == awq.max_num_seqs and int(env["MAX_MODEL_LEN"]) == plan.model_len(awq)
    assert "HEALTHCHECK" in text and "/health" in text and "--enable-prefix-caching" in text
