"""Render DATA_CARD.md from data/processed/stats.json (numbers are never typed by hand)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from jobx.schema import FIELD_ORDER


def _tbl(header: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _dist(d: dict[str, Any], n: int) -> str:
    return (
        ", ".join(f"{'not stated' if k == 'None' else k} {v} ({v / n:.0%})" for k, v in d.items())
        if n
        else "-"
    )


def render(stats: dict[str, Any], real: dict[str, Any] | None = None) -> str:
    p = stats["pipeline"]
    sp = stats["splits"]
    tr = sp["train"]
    cfg = stats["config"]
    fam = cfg["families"]
    lines: list[str] = []
    a = lines.append
    a("# Data card: jobpost-extractor-qlora")
    a("")
    a("_Generated by `jobx build-data` from `data/processed/stats.json`. Do not edit by hand._")
    a("")
    a("## Summary")
    a("")
    a(
        _tbl(
            ["split", "examples", "source", "template families", "distinct companies"],
            [
                [
                    s,
                    sp[s]["n"],
                    ", ".join(f"{k} {v}" for k, v in sp[s].get("sources", {}).items()),
                    ", ".join(fam.get(s, [])),
                    sp[s].get("distinct_companies", 0),
                ]
                for s in sp
            ]
            + [["test_real", real["n"] if real else "pending", "real public postings (see below)", "-", "-"]],
        )
    )
    a("")
    a(
        "The headline evaluation is **test_real** (real postings, human-verified). `test_synth` uses template "
        "families and companies never seen in training, so it measures generalisation beyond the templates, "
        "but it is still synthetic."
    )
    a("")
    a("## Sources")
    a("")
    a(
        "1. **Synthetic, labels by construction** (`src/jobx/data/`). A structured record is sampled first "
        "(company, role, seniority, skills, experience, salary, cities, work mode, employment type, education), "
        "then rendered to text through alias tables, one of "
        f"{sum(len(v) for v in fam.values())} template families and noise operators. The label is the sampled "
        "record, so it is exact; no model labels anything."
    )
    a(
        "2. **Paraphrases** of a training subset by an open 7B instruct model (notebook `01_paraphrase_7b`), "
        "kept only if the rule + NLI checker passes. "
        + (
            "Filter results below."
            if stats.get("paraphrase_filter")
            else "**Pending GPU run**: not yet included."
        )
    )
    a(
        "3. **Real postings** from a public Hugging Face dataset for `test_real`, labelled by a strong-model draft "
        "plus human verification with `jobx verify`. "
        + (
            f"{real['n']} examples from `{real.get('dataset')}`."
            if real
            else "**Pending**: see `docs/real_dataset.md` (licence check is a TODO)."
        )
    )
    a("")
    a(
        "Company names are fictional (compositional, e.g. stem + sector); any resemblance to a real company is "
        "coincidental. Phone numbers, e-mails and links in the text are random placeholders "
        "(`careers.example.in`)."
    )
    a("")
    a("## Pipeline and filter statistics")
    a("")
    a(
        _tbl(
            ["step", "count"],
            [
                ["generated (before filtering)", p["generated"]],
                ["failed field-recoverability check", p["validation_failed"]],
                ["paraphrases added", p["paraphrased_added"]],
                ["dropped: family/company split mismatch", p["dropped_family_company_mismatch"]],
                ["exact duplicates removed", p["exact_duplicates_removed"]],
                [
                    "near-duplicates removed (MinHash, Jaccard >= "
                    f"{cfg['dedup']['threshold']} on word {cfg['dedup']['shingle_words']}-grams)",
                    p["near_duplicates_removed"],
                ],
                ["of which across splits (leakage prevented)", p["duplicates_removed_across_splits"]],
                ["**final**", f"**{p['final_total']}**"],
            ],
        )
    )
    if p["validation_failures_by_field"]:
        a("")
        a(
            "Recoverability failures by field: "
            + ", ".join(f"{k} {v}" for k, v in p["validation_failures_by_field"].items())
        )
    pf = stats.get("paraphrase_filter")
    if pf:
        a("")
        a(
            f"Paraphrase filter: {pf.get('kept', '?')} kept of {pf.get('attempted', '?')} "
            f"({pf.get('filter_rate', '?')} filtered). Reasons: {pf.get('reasons', {})}"
        )
    a("")
    a(
        "**Leakage check:** template families and companies are disjoint across splits: "
        f"**{'pass' if stats['leakage']['ok'] else 'FAIL'}**. Near-duplicates are resolved in favour of the "
        "test/val copy, so the removed copy is always the training one."
    )
    a("")
    a("## Field distributions (train)")
    a("")
    n = tr["n"]
    a("Share of postings where each field is stated (otherwise gold is `null` / `[]`):")
    a("")
    a(_tbl(["field", *sp.keys()], [[f, *[sp[s]["field_presence"][f] for s in sp]] for f in FIELD_ORDER]))
    a("")
    a(f"- Seniority: {_dist(tr['seniority'], n)}")
    a(f"- Work mode: {_dist(tr['work_mode'], n)}")
    a(f"- Employment type: {_dist(tr['employment_type'], n)}")
    a(f"- Education: {_dist(tr['education'], n)}")
    a(
        f"- Salary period: {tr['salary_period']}; currency: {tr['salary_currency']}; open-ended (upto/min only): "
        f"{tr['salary_open_ended']}"
    )
    a(f"- Salary midpoint, LPA (INR per annum / 1e5) quantiles: {tr['salary_mid_lpa_quantiles']}")
    a(
        f"- Skills per posting quantiles: {tr['n_skills_quantiles']}; locations per posting: {tr['n_locations']}"
    )
    a(f"- Text length (characters) quantiles: {tr['text_chars_quantiles']}")
    a(f"- Domains: {tr['domains']}")
    a(f"- Noise operators applied (counts): {tr['noise_ops']}")
    a(f"- 'Headquartered in <other city>' location trap: {tr['hq_trap_rate']:.1%} of postings")
    a("")
    a("Top skills: " + ", ".join(f"{k} ({v})" for k, v in tr["top_skills"].items()))
    a("")
    a("Top cities: " + ", ".join(f"{k} ({v})" for k, v in tr["top_locations"].items()))
    a("")
    a("## Known biases and limitations")
    a("")
    a(
        "- **Template artefacts.** However many families and noise operators, synthetic text has regularities a "
        "model can learn. That is why the headline number is on real postings."
    )
    a(
        "- **Short texts.** Synthetic postings are shorter than many real job descriptions (median above); "
        "long real JDs with long boilerplate are under-represented."
    )
    a(
        "- **Vocabulary coverage.** Skills, cities and degrees come from fixed alias tables "
        "(`src/jobx/vocab.py`). Skills outside the table are never in synthetic gold labels."
    )
    a(
        "- **Salary bands** are plausible ranges by seniority for tech vs non-tech, not survey data. "
        "USD salaries appear only for a few remote roles and are converted at a fixed 83 INR/USD."
    )
    a(
        "- **Metro skew** is deliberate (Bengaluru, Hyderabad, Pune, Chennai, NCR dominate) and mirrors job "
        "boards, so tier-2/3 cities are rarer."
    )
    a(
        "- **Seniority** is labelled only when stated in words; it is never inferred from experience, so a model "
        "that infers it is penalised as hallucinating."
    )
    a("- **English-first.** Hinglish appears as fragments and one held-out family, not full Hindi postings.")
    a("")
    a("## Licence")
    a("")
    a(
        "Synthetic data and generator code: MIT (this repository). Real postings: the licence of the source "
        "dataset applies; see `docs/real_dataset.md`."
    )
    a("")
    a("## Reproduce")
    a("")
    a("```bash")
    a("pip install -e .")
    a("jobx build-data            # writes data/processed/*.jsonl, stats.json and DATA_CARD.md")
    a("```")
    a("")
    a(f"Seed `{cfg['seed']}`, config `configs/data.yaml`.")
    a("")
    return "\n".join(lines)


def write_datacard(stats_path: str | Path, out_path: str | Path, real_meta: str | Path | None = None) -> None:
    stats = json.loads(Path(stats_path).read_text())
    real = None
    if real_meta and Path(real_meta).exists():
        real = json.loads(Path(real_meta).read_text())
    Path(out_path).write_text(render(stats, real))
