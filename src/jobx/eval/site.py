def build_site(root: str | Path = ".", out: str | Path = "site") -> Path:
    root, out = Path(root), Path(out)
    out.mkdir(parents=True, exist_ok=True)
    md = (root / "results/results_table.md").read_text()
    curves = ""
    png = root / "results/training/curves.png"
    if png.exists():
        shutil.copy(png, out / "curves.png")
        curves = '<h2>Training curves</h2><img src="curves.png" alt="training and validation loss curves">'
    (out / "index.html").write_text(PAGE.format(body=md_to_html(md), curves=curves))
    for name in ("results.json",):
        src = root / "results" / name
        if src.exists():
            shutil.copy(src, out / name)
    return out / "index.html"
