"""Failure analysis of one approach on one split, generated from committed predictions.

    jobx failures --approach qwen2.5-0.5b-lora-cpu_q4_k_m --split test_real

Writes ``results/failures/<approach>__<split>.md``: per-field error counts split into missed (gold stated,
prediction null), hallucinated (gold null, prediction filled), wrong value, and partial lists; whether wrong
values were supported by the text (evidence), and a few concrete examples per field with a text excerpt.
Examples are the first ones in id order, not hand-picked.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

from jobx.data.build import read_jsonl
from jobx.eval.metrics import score_example
from jobx.eval.run import SPLIT_FILES
from jobx.evidence import evidence_by_field, find_evidence
from jobx.schema.models import FIELD_ORDER, LIST_FIELDS


def _short(v: Any, n: int = 90) -> str:
    s = json.dumps(v, ensure_ascii=False)
    return s if len(s) <= n else s[: n - 1] + "…"


def _excerpt(text: str, needle: Any, n: int = 160) -> str:
    t = " ".join(text.split())
    if isinstance(needle, str) and needle:
        i = t.lower().find(needle.lower())
        if i >= 0:
            a = max(0, i - n // 2)
            return ("…" if a else "") + t[a : a + n] + ("…" if a + n < len(t) else "")
    return t[:n] + ("…" if len(t) > n else "")


def analyse(
    approach: str, split: str, root: Path = Path("."), *, examples_per_field: int = 3
) -> dict[str, Any]:
    gold = {g["id"]: g for g in read_jsonl(root / SPLIT_FILES[split])}
    preds = read_jsonl(root / "results/predictions" / f"{approach}__{split}.jsonl")
    kinds: dict[str, Counter[str]] = {f: Counter() for f in FIELD_ORDER}
    examples: dict[str, list[dict[str, Any]]] = {f: [] for f in FIELD_ORDER}
    n = invalid = 0
    for p in sorted(preds, key=lambda x: x["id"]):
        g = gold.get(p["id"])
        if g is None:
            continue
        n += 1
        s = score_example(p["id"], g["label"], p.get("output") or "", g.get("label_alternatives"))
        if not s.json_ok:
            invalid += 1
            continue
        ev = evidence_by_field(find_evidence(g["text"], s.pred))
        for f in FIELD_ORDER:
            fs = s.fields[f]
            if fs.correct:
                continue
            if f in LIST_FIELDS:
                kind = "missed all" if fs.pred_null else "spurious only" if fs.gold_null else "partial list"
            else:
                kind = "missed" if fs.pred_null else "hallucinated" if fs.gold_null else "wrong value"
            kinds[f][kind] += 1
            if not fs.pred_null:
                kinds[f][f"pred {ev.get(f, 'unsupported')} by text"] += 1
            if len(examples[f]) < examples_per_field:
                examples[f].append(
                    {
                        "id": p["id"],
                        "gold": g["label"].get(f),
                        "pred": s.pred.get(f),
                        "kind": kind,
                        "evidence": ev.get(f) if not fs.pred_null else None,
                        "excerpt": _excerpt(
                            g["text"], s.pred.get(f) if isinstance(s.pred.get(f), str) else g["label"].get(f)
                        ),
                    }
                )
    return {
        "approach": approach,
        "split": split,
        "n": n,
        "invalid_json": invalid,
        "kinds": {f: dict(c) for f, c in kinds.items()},
        "examples": examples,
    }


def render(rep: dict[str, Any]) -> str:
    out = [
        f"# Failure analysis: `{rep['approach']}` on `{rep['split']}`",
        "",
        f"Generated by `jobx failures` from committed predictions ({rep['n']} postings, {rep['invalid_json']} without valid JSON). "
        'Error kinds per field; "pred supported/weak/unsupported by text" says whether the wrong predicted value can be '
        "found in the posting (evidence alignment), which separates convention or labelling disagreements from invented values.",
        "",
        "| Field | Errors | Breakdown |",
        "|---|---|---|",
    ]
    for f in FIELD_ORDER:
        k = rep["kinds"][f]
        main = {x: v for x, v in k.items() if not x.startswith("pred ")}
        evid = {x: v for x, v in k.items() if x.startswith("pred ")}
        total = sum(main.values())
        parts = ", ".join(f"{x} {v}" for x, v in sorted(main.items(), key=lambda kv: -kv[1]))
        if evid:
            parts += (
                " ("
                + ", ".join(
                    f"{x.removeprefix('pred ')} {v}" for x, v in sorted(evid.items(), key=lambda kv: -kv[1])
                )
                + ")"
            )
        out.append(f"| {f} | {total} | {parts or '-'} |")
    out += ["", "## Examples (first errors in id order, not hand-picked)", ""]
    for f in FIELD_ORDER:
        if not rep["examples"][f]:
            continue
        out.append(f"### {f}")
        out.append("")
        for e in rep["examples"][f]:
            ev = f", prediction {e['evidence']} by the text" if e["evidence"] else ""
            out.append(
                f"- `{e['id']}` ({e['kind']}{ev}): label {_short(e['gold'])} vs predicted {_short(e['pred'])}  "
            )
            out.append(f"  > {e['excerpt']}")
        out.append("")
    return "\n".join(out)


def write(approach: str, split: str, root: Path = Path(".")) -> Path:
    rep = analyse(approach, split, root)
    dest = root / "results/failures" / f"{approach}__{split}.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(render(rep) + "\n")
    return dest
